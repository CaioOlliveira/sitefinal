import { chromium } from 'playwright-core'

const browser = await chromium.launch({ executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: true })
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
page.on('pageerror', error => console.error('PAGE ERROR:', error.message))
try {
  await page.goto('http://127.0.0.1:5174/', { waitUntil: 'networkidle' })
  await page.locator('.hero .button').click()
  await page.locator('.product-card').first().click()
  await page.locator('.size-list button').getByText('38').click()
  await page.getByRole('button', { name: /ADICIONAR AO CARRINHO/ }).click()
  await page.getByRole('link', { name: /Ver carrinho/ }).click()
  await page.locator('.cart-item').first().waitFor()
  console.log('cart items:', await page.locator('.cart-item').count())
  await page.locator('.shipping-estimator input').fill('01001000')
  await page.getByRole('button', { name: 'CALCULAR' }).click()
  await page.getByText(/São Paulo \/ SP/).waitFor()
  console.log('shipping:', await page.locator('.shipping-estimator small').textContent())
  await page.getByRole('button', { name: /FINALIZAR COMPRA/ }).click()
  await page.getByLabel('E-mail').fill('teste@exemplo.com')
  await page.getByLabel('Senha').fill('senhateste')
  await page.getByRole('button', { name: /ENTRAR NA MINHA CONTA/ }).click()
  await page.waitForURL('**/checkout')
  await page.locator('.address-grid input').nth(0).fill('01001000')
  await page.locator('.address-grid .input-action button').click()
  await page.getByText(/Endereço encontrado/).waitFor()
  await page.locator('.address-grid input').nth(2).fill('100')
  await page.getByRole('button', { name: /CONFIRMAR PEDIDO/ }).click()
  await page.waitForTimeout(1200)
  console.log('after confirmation click:', page.url(), (await page.locator('.form-message').allTextContents()).join(' | '))
  await page.waitForURL('**/pedido/*')
  console.log('confirmation:', await page.locator('.success-page h1').textContent())
  await page.getByRole('link', { name: /VER MEUS PEDIDOS/ }).click()
  await page.locator('.order-card').first().waitFor()
  console.log('orders:', await page.locator('.order-card').count())
} finally {
  await browser.close()
}
